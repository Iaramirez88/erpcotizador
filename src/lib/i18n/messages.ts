export type TranslateVars = Record<string, string | number>

function escapeRegExp(input: string) {
  return input.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

export function translate(language: UiLanguage, key: string, vars?: TranslateVars) {
  const msg = MESSAGES[language]?.[key]
  const base = typeof msg === 'string' && msg ? msg : MESSAGES[DEFAULT_LANGUAGE]?.[key]
  const text = typeof base === 'string' && base ? base : key

  if (!vars) return text

  return Object.entries(vars).reduce((acc, [k, v]) => {
    const re = new RegExp(`\\{${escapeRegExp(k)}\\}`, 'g')
    return acc.replace(re, String(v))
  }, text)
}
